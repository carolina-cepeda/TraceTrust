"""Neo4j projection adapter and deterministic Cypher export."""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

from .models import GraphEdge, GraphNode, TraceGraphArtifact


RELATION_PATTERN = re.compile(r"^[A-Z][A-Z0-9_]*$")


def _relation_type(relation: str) -> str:
    candidate = re.sub(r"[^A-Za-z0-9_]", "_", relation).upper()
    if not candidate or not RELATION_PATTERN.fullmatch(candidate):
        raise ValueError(f"Invalid graph relation: {relation}")
    return candidate


def _node_properties(node: GraphNode) -> dict[str, str]:
    snapshot_id = str(node.properties.get("snapshot_id", ""))
    return {
        "id": node.id,
        "node_type": node.node_type,
        "label": node.label,
        "snapshot_id": snapshot_id,
        "properties_json": json.dumps(node.properties, ensure_ascii=False, sort_keys=True),
    }


def export_cypher(artifact: TraceGraphArtifact, output: str | Path) -> None:
    """Write idempotent Cypher using parameter maps for data values."""
    lines = [
        "// Generated by TraceTrust. PostgreSQL remains the source of truth.",
        "// Apply schemas/tracetrust-neo4j/001_constraints.cypher first.",
        "",
        "UNWIND $nodes AS node",
        "MERGE (n:TraceNode {id: node.id})",
        "SET n.node_type = node.node_type, n.label = node.label,",
        "    n.snapshot_id = node.snapshot_id, n.properties_json = node.properties_json;",
        "",
    ]
    node_params = [_node_properties(node) for node in artifact.nodes]
    for relation in sorted({_relation_type(edge.relation) for edge in artifact.edges}):
        lines.extend([
            f"// Relationship type: {relation}",
            f"UNWIND $edges_{relation} AS edge",
            "MATCH (source:TraceNode {id: edge.source})",
            "MATCH (target:TraceNode {id: edge.target})",
            f"MERGE (source)-[r:{relation}]->(target)",
            "SET r.properties_json = edge.properties_json;",
            "",
        ])
    edge_groups: dict[str, list[dict[str, str]]] = {}
    for edge in artifact.edges:
        relation = _relation_type(edge.relation)
        edge_groups.setdefault(relation, []).append({
            "source": edge.source, "target": edge.target,
            "properties_json": json.dumps(edge.properties, ensure_ascii=False, sort_keys=True),
        })
    payload = {"nodes": node_params, **{f"edges_{key}": value for key, value in edge_groups.items()}}
    output_path = Path(output)
    output_path.write_text("\n".join(lines) + "\n// Parameters:\n" + json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")


def push_neo4j(artifact: TraceGraphArtifact, uri: str, username: str, password: str, database: str = "neo4j") -> None:
    """Push a graph through the official driver when Neo4j is available."""
    try:
        from neo4j import GraphDatabase
    except ImportError as exc:
        raise RuntimeError("Install tracetrust[neo4j] to push a projection") from exc
    driver = GraphDatabase.driver(uri, auth=(username, password))
    try:
        with driver.session(database=database) as session:
            session.run(
                "UNWIND $nodes AS node MERGE (n:TraceNode {id: node.id}) "
                "SET n.node_type=node.node_type, n.label=node.label, n.snapshot_id=node.snapshot_id, "
                "n.properties_json=node.properties_json",
                nodes=[_node_properties(node) for node in artifact.nodes],
            ).consume()
            for relation in sorted({_relation_type(edge.relation) for edge in artifact.edges}):
                edges = [{
                    "source": edge.source, "target": edge.target,
                    "properties_json": json.dumps(edge.properties, ensure_ascii=False, sort_keys=True),
                } for edge in artifact.edges if _relation_type(edge.relation) == relation]
                session.run(
                    f"UNWIND $edges AS edge MATCH (source:TraceNode {{id: edge.source}}) "
                    f"MATCH (target:TraceNode {{id: edge.target}}) MERGE (source)-[r:{relation}]->(target) "
                    "SET r.properties_json=edge.properties_json",
                    edges=edges,
                ).consume()
    finally:
        driver.close()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("graph", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    artifact = TraceGraphArtifact.model_validate_json(args.graph.read_text(encoding="utf-8"))
    export_cypher(artifact, args.output)
    print(json.dumps({"nodes": len(artifact.nodes), "edges": len(artifact.edges), "output": str(args.output)}, indent=2))


if __name__ == "__main__":
    main()
